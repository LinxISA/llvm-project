#!/usr/bin/env python3
"""Generate the scoped Scalar form whitelist from the exact LinxISA import."""

import argparse
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / "lib/Target/LinxISA/MCTargetDesc"
LINX_COMMIT = "2a29daf7ed6ea33c1719c27abd1ac48d2e75b1cd"
CATALOG_SHA256 = "5c01ea73c09305284ee00dbc4bd869925662af80d564c706761b59b9bc592c67"
SCOPED_SHA256 = "0f9ab05d6a7547d970b8f2a21b158a5b993527df42445ab494ed8acea0462c16"
PTO_LOCK_SHA256 = "a526f6dbbddfe67d349640f19e904c1148a24178b0ec697f4dc360ddac624f34"


def locked_json(path, expected):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError(f"{path} must come from LinxISA {LINX_COMMIT}")
    return json.loads(data)


def packed_encoding(parts):
    mask = match = offset = 0
    for part in parts:
        mask |= int(part["mask"], 0) << offset
        match |= int(part["match"], 0) << offset
        offset += part["width_bits"]
    return offset, mask, match


def render(linx_dir):
    linx = locked_json(linx_dir / "isa/v0.58/linxisa-v0.58.json", CATALOG_SHA256)
    pto = locked_json(linx_dir / "isa/v0.59/state/pto_scalar_forms.json", SCOPED_SHA256)
    mapped = {r["pto_source_form_id"]: r["id"] for r in linx["instructions"] if "pto_source_form_id" in r}
    bases = {r["form_id"]: r for r in pto["forms"]}
    scoped = {}
    for row in pto["scoped_forms"]:
        scoped.setdefault(row["base_form_id"], []).append(row)
    if len(scoped) != 235 or len(pto["scoped_forms"]) != 705:
        raise ValueError("unexpected scoped Scalar inventory")

    table = (TABLES / "linxisa_opcodes.c").read_text().split("const linxisa_inst_form linxisa_inst_forms[] = {", 1)[1].split("};", 1)[0]
    entries = re.findall(r'\.id = "([^"]+)".*?\.length_bits = (\d+), \.mask = (0x\w+?)ULL, \.match = (0x\w+?)ULL', table)
    compiled = {row[0]: (int(row[1]), int(row[2], 0), int(row[3], 0)) for row in entries}

    forms = []
    witnesses = []
    for identity, rows in scoped.items():
        base = bases[identity]
        width, mask, match = compiled[mapped[identity]]
        if packed_encoding(base["encoding"]) != (width, mask, match):
            raise ValueError(f"MC encoding differs for {identity}")
        if any(c["field"] != "SrcRType" or c["operator"] != "one-of" or c["values"] != [0, 1, 2] for c in base["constraints"]):
            raise ValueError(f"new legality constraint for {identity}")
        if len(rows) != 3 or {row["scope_code"] for row in rows} != {0, 1, 2}:
            raise ValueError(f"incomplete scopes for {identity}")
        for row in rows:
            scope = row["scope_code"]
            padding = ((1 << 48) - 1) ^ ((1 << width) - 1)
            prefix = 0x001F | ({16: 0, 32: 1, 48: 2}[width] << 10) | (scope << 8)
            expected = (64, ((mask | padding) << 16) | 0xFFFF, (match << 16) | prefix)
            if packed_encoding(row["encoding"]) != expected:
                raise ValueError(f"incompatible carrier for {row['form_id']}")
            suffix = (".private", ".intra", ".inter")[scope]
            witnesses.append((expected[2], base["mnemonic"].lower() + suffix))
        forms.append(mapped[identity])

    lines = [
        "// Generated by llvm/utils/linxisa/gen_scoped_scalar_forms.py.",
        f"// LinxISA input revision {LINX_COMMIT}.",
        "// Each entry is a stable ID from the generated LinxISA MC forms.",
    ]
    lines += [f'"{identity}",' for identity in sorted(forms)]
    return "\n".join(lines) + "\n", witnesses


def render_identity(linx_dir):
    lock = locked_json(linx_dir / "isa/v0.59/pto-spec.lock.json", PTO_LOCK_SHA256)
    keys = ("encoding_abi", "encoding_projection_sha256", "release")
    identity = json.dumps({key: lock[key] for key in keys}, separators=(",", ":"))
    return (
        "// Generated by llvm/utils/linxisa/gen_scoped_scalar_forms.py.\n"
        f"// PTO source revision {lock['source']['commit']}.\n"
        f"{json.dumps(identity)}\n"
    )


def verify_mc(tool_dir, witnesses):
    with tempfile.TemporaryDirectory(prefix="linx-scoped-disassembly-") as tmp:
        obj = Path(tmp) / "witnesses.o"
        asm = ".text\n" + "".join(f".8byte 0x{word:016x}\n" for word, _ in witnesses)
        subprocess.run(
            [tool_dir / "llvm-mc", "-triple=linx64", "-filetype=obj", "-o", obj],
            input=asm, text=True, check=True,
        )
        output = subprocess.check_output(
            [tool_dir / "llvm-objdump", "-d", "--no-show-raw-insn", "--triple=linx64", obj],
            text=True,
        )
    actual = re.findall(r"^\s*([0-9a-f]+):[ \t]+(\S+)([^\n]*)", output, re.MULTILINE)
    if len(actual) != len(witnesses):
        raise ValueError(f"decoded {len(actual)} instructions, expected {len(witnesses)}")
    sources = []
    for index, ((address, mnemonic, operands), (_, expected)) in enumerate(zip(actual, witnesses, strict=True)):
        if int(address, 16) != 8 * index or mnemonic.lower() != expected:
            raise ValueError(f"witness {index}: got {mnemonic} at {address}, expected {expected} at {8 * index:x}")
        sources.append(mnemonic + re.sub(r"\s+<[^<>]*>$", "", operands.rstrip()))

    assembled = subprocess.run(
        [tool_dir / "llvm-mc", "-triple=linx64", "-mattr=+pto-v0591-scoped", "-show-encoding"],
        text=True, input="\n".join(sources) + "\n", stdout=subprocess.PIPE, check=True,
    ).stdout
    results = re.findall(r"encoding: \[([^]]+)\]", assembled)
    if len(results) != len(witnesses):
        raise ValueError(f"assembled {len(results)} instructions, expected {len(witnesses)}")
    for index, (encoding, (word, _)) in enumerate(zip(results, witnesses, strict=True)):
        encoded = bytes(int(value, 0) for value in encoding.split(","))
        if encoded != word.to_bytes(8, "little"):
            raise ValueError(f"witness {index} did not round trip: {sources[index]}")
    print(f"Round-tripped all {len(witnesses)} scoped Scalar carrier witnesses")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("linx_dir", type=Path, help="LinxISA checkout at the locked revision")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tool-dir", type=Path, help="Verify every witness with built LLVM tools")
    args = parser.parse_args()
    forms, witnesses = render(args.linx_dir)
    outputs = {
        "LinxISAScopedScalarForms.inc": forms,
        "LinxISAScopedScalarIdentity.inc": render_identity(args.linx_dir),
    }
    for name, expected in outputs.items():
        output = TABLES / name
        if args.check:
            if output.read_text() != expected:
                raise SystemExit(f"stale generated output: {output}")
        else:
            output.write_text(expected)
    if args.tool_dir:
        verify_mc(args.tool_dir.resolve(), witnesses)


if __name__ == "__main__":
    main()
