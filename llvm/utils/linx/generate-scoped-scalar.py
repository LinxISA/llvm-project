#!/usr/bin/env python3
"""Generate scoped instructions from LLVM operand definitions and pinned PTO forms.

Usage: generate-scoped-scalar.py --records <llvm-tblgen -dump-json output>
The pinned manifest contains only the normative covered mnemonic/encoding set.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'lib/Target/LinxV5'


def generate(records, manifest):
    covered = {f['mnemonic'].lower() for f in manifest['forms']}
    def family(mnemonic):
        if mnemonic in covered:
            return mnemonic
        stem, _, order = mnemonic.rpartition('.')
        if order in ('aq', 'rl', 'aqrl', 'f', 'aqf', 'rlf', 'aqrlf') and stem in covered:
            return stem
        return mnemonic
    bases = [(n, r) for n, r in records.items() if isinstance(r, dict)
             and r.get('AsmString', '').split()[:1]
             and family(r['AsmString'].split()[0]) in covered and not r.get('isPseudo')
             and not n.startswith(('SCOPED_', 'CG_SCOPED_'))]
    assert {family(r['AsmString'].split()[0]) for _, r in bases} == covered
    forms = {f['mnemonic'].lower(): f for f in manifest['forms']}
    for name, record in bases:
        form = forms[family(record['AsmString'].split()[0])]
        assert record['Size'] * 8 == form['length_bits'], name
        mask = sum(int(e['mask'], 16) << (e['index'] * 32) for e in form['encoding'])
        match = sum(int(e['match'], 16) << (e['index'] * 32) for e in form['encoding'])
        bits = record['Inst']
        for i in range(form['length_bits']):
            if mask & (1 << i):
                assert bits[i] == ((match >> i) & 1), (name, i)
        for constraint in form['constraints']:
            assert constraint['field'] == 'SrcRType' and constraint['operator'] == 'one-of'
            # Operand modifiers are fixed per LLVM record, never unconstrained.
            value, index = 0, 0
            for i in range(form['length_bits']):
                if not mask & (1 << i) and isinstance(bits[i], int):
                    value |= bits[i] << index
                    index += 1
            assert value in constraint['values'], (name, value)
    td = ['// Generated by llvm/utils/linx/generate-scoped-scalar.py.\n',
          '// PTO-ISA #416; do not edit generated instruction definitions.\n',
          'class ScopedScalar<Instruction Base, bits<2> Scope> : LinxV5InstBase {\n',
          '  field bits<64> Inst = 0;\n  field bits<64> SoftFail = 0;\n',
          '  let Size = 8;\n  let OutOperandList = Base.OutOperandList;\n',
          '  let InOperandList = Base.InOperandList;\n',
          '  let Pattern = [];\n  let TSFlags = Base.TSFlags;\n',
          '  let TSFlags{21-20} = Scope;\n  let TSFlags{22} = 1;\n']
    for prop in ['Uses', 'Defs', 'Constraints', 'Predicates', 'SchedRW', 'Itinerary',
                 'mayLoad', 'mayStore', 'hasSideEffects', 'hasCtrlDep',
                 'isConvergent', 'isNotDuplicable', 'DecoderMethod',
                 'hasCompleteDecoder', 'AsmMatchConverter']:
        td.append(f'  let {prop} = Base.{prop};\n')
    td.append('}\n\n')
    mapping = ['// Generated by llvm/utils/linx/generate-scoped-scalar.py.\n']
    for name, r in sorted(bases):
        size = r['Size']
        assert size in (2, 4, 6)
        mnemonic = r['AsmString'].split()[0]
        block_start = len(td)
        td.append(f'foreach Scope = 0-2 in {{\n  def "SCOPED_{name}_" # Scope : ScopedScalar<{name}, Scope> {{\n')
        asm = [r['AsmString'].replace(mnemonic, mnemonic+'.'+s, 1) for s in ['private','intra','inter']]
        td.append('    let AsmString = !if(!eq(Scope, 0), '+json.dumps(asm[0])+', !if(!eq(Scope, 1), '+json.dumps(asm[1])+', '+json.dumps(asm[2])+'));\n')
        fields = {}
        for bit in r['Inst']:
            if isinstance(bit, dict):
                fields[bit['var']] = max(fields.get(bit['var'], 0), bit['index']+1)
        for field, width in sorted(fields.items()):
            td.append(f'    bits<{width}> {field};\n')
        td.append(f'    let Inst{{15-0}} = 0x{(size//2-1)*1024+31:04x};\n    let Inst{{9-8}} = Scope;\n')
        for i, bit in enumerate(r['Inst']):
            if bit == 0:
                continue
            val = str(bit) if isinstance(bit, int) else f"{bit['var']}{{{bit['index']}}}"
            assert bit is not None
            td.append(f'    let Inst{{{i+16}}} = {val};\n')
        td.append('  }\n}\n\n')
        mapping.append(f'SCOPED_SCALAR({name}, SCOPED_{name}_0, SCOPED_{name}_1, SCOPED_{name}_2)\n')
        if name in ('LBUI', 'LHUI', 'LWUI', 'LDI', 'SBI', 'SHI', 'SWI', 'SDI') or (
                not mnemonic.startswith(('hl.', 'c.')) and
                family(mnemonic).startswith(('lr.', 'sc.', 'swap', 'cas', 'lw.', 'ld.'))):
            block = ''.join(td[block_start:])
            block = block.replace(f'SCOPED_{name}_', f'CG_SCOPED_{name}_')
            extras = '    let isCodeGenOnly = 1;\n'
            for prop, op in [('OutOperandList', 'outs'), ('InOperandList', 'ins')]:
                operands, names = [], []
                for i, (operand, arg) in enumerate(r[prop]['args']):
                    operands.append('GR' if operand['def'] in ('GPRSrc', 'DstRWithArrow')
                                    else 'simm12')
                    names.append(json.dumps(arg))
                extras += (f'    let {prop} = !dag({op}, [' + ', '.join(operands) + '], [' + ', '.join(names) + ']);\n') if operands else f'    let {prop} = ({op});\n'
            td.append(block.replace('    let AsmString', extras + '    let AsmString', 1))
            mapping.append(f'CG_SCOPED_SCALAR({name}, CG_SCOPED_{name}_0, CG_SCOPED_{name}_1, CG_SCOPED_{name}_2)\n')

    return {TARGET/'LinxV5ScopedScalar.td': ''.join(td).rstrip() + '\n',
            TARGET/'MCTargetDesc/LinxV5ScopedScalar.inc': ''.join(mapping)}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--records', type=Path, required=True)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    manifest = json.loads((Path(__file__).with_name('scoped-scalar-forms.json')).read_text())
    for path, content in generate(json.loads(args.records.read_text()), manifest).items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'stale generated file: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
