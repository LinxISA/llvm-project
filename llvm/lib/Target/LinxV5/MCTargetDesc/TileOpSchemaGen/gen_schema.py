#!/usr/bin/env python3
"""Generate the compact LinxV5 TileOp macro-assembly schema table from the
PTO catalog (pto-spec #263, catalog tree b50ed858).

The generated table is data-only: it maps macro fields/forms to the
already-supported physical MC layer (BSTART/B.DATR/B.DIM/B.IOR/B.IOT/B.IOS).
Generation fails closed on unknown commands, fields, binding kinds, or
physical slots."""
import json, hashlib, sys, datetime

CATALOG = sys.argv[1] if len(sys.argv) > 1 else '/tmp/tile-macro-assembly.json'
OUT = sys.argv[2] if len(sys.argv) > 2 else '/tmp/macro_asm/LinxV5TileOpSchema.inc'

KNOWN_COMMANDS = {'BSTART.GMOV','BSTART.MGATHER','BSTART.MGATHER.ADD','BSTART.MGATHER.AND','BSTART.MGATHER.CAS','BSTART.MGATHER.DEC','BSTART.MGATHER.EXCH','BSTART.MGATHER.INC','BSTART.MGATHER.MASK','BSTART.MGATHER.MAX','BSTART.MGATHER.MIN','BSTART.MGATHER.OR','BSTART.MGATHER.XOR','BSTART.MSCATTER','BSTART.MSCATTER.ADD','BSTART.MSCATTER.AND','BSTART.MSCATTER.DEC','BSTART.MSCATTER.INC','BSTART.MSCATTER.MASK','BSTART.MSCATTER.MAX','BSTART.MSCATTER.MIN','BSTART.MSCATTER.OR','BSTART.MSCATTER.POPC','BSTART.MSCATTER.XOR','BSTART.SFU','BSTART.TGEMV','BSTART.TGEMV.ACC','BSTART.TGEMV.BIAS','BSTART.TGEMVMX','BSTART.TGEMVMX.ACC','BSTART.TGEMVMX.BIAS','BSTART.TLOAD','BSTART.TMATMUL','BSTART.TMATMUL.ACC','BSTART.TMATMUL.BIAS','BSTART.TMATMULMX','BSTART.TMATMULMX.ACC','BSTART.TMATMULMX.BIAS','BSTART.TMOV','BSTART.TPREFETCH','BSTART.TSTORE','BSTART.VEC',
                  'B.DATR','B.FPATR','B.DIM','B.IOR','B.IOT','B.IOS','BSTOP'}
KNOWN_BINDING_KINDS = {'bundle-configuration','scalar-binding','tile-source-binding',
    'tile-destination-binding','shared-tile-binding','predicate-tile-source',
    'predicate-tile-destination','predicate-cell-source','predicate-cell-destination',
    'predicate-gpr-source','predicate-gpr-destination'}
KNOWN_CONFIG_KINDS = {'attribute','dimension'}
KNOWN_VALUE_STYLES = {'bare-value','named-role'}

d = json.load(open(CATALOG))
raw = open(CATALOG,'rb').read()
digest = hashlib.sha256(raw).hexdigest()

def fail(msg):
    print(f'GENERATION ERROR: {msg}', file=sys.stderr); sys.exit(1)

# ---- validation pass ----
ops = d['operations']
if len(ops) != 117: fail(f'expected 117 operations, got {len(ops)}')
total_forms = 0
for op in ops:
    forms = op.get('forms') or []
    if not forms:
        # single implicit form from op-level fields
        forms = [None]
    for f in forms:
        total_forms += 1
        base = f if f else op
        for sec in ('configuration','sources','destinations'):
            for item in base.get(sec, []):
                if item['binding_kind'] not in KNOWN_BINDING_KINDS:
                    fail(f"{op['mnemonic']}: unknown binding_kind {item['binding_kind']}")
                ck = item.get('configuration_kind')
                if ck and ck not in KNOWN_CONFIG_KINDS:
                    fail(f"{op['mnemonic']}: unknown configuration_kind {ck}")
                vs = item.get('value_style')
                if vs and vs not in KNOWN_VALUE_STYLES:
                    fail(f"{op['mnemonic']}: unknown value_style {vs}")
        exp = (f or op).get('expansion', {})
        for b in exp.get('configuration_bindings', []):
            cmd = b.get('command')
            if cmd and cmd not in KNOWN_COMMANDS:
                fail(f"{op['mnemonic']}: unknown command {cmd}")
        for b in exp.get('operand_bindings', []):
            cmd = b.get('command')
            if cmd and cmd not in KNOWN_COMMANDS:
                fail(f"{op['mnemonic']}: unknown command {cmd}")
        hdr_cmd = exp.get('header', {}).get('command')
        if hdr_cmd and hdr_cmd not in KNOWN_COMMANDS:
            fail(f"{op['mnemonic']}: unknown header command {hdr_cmd}")
if total_forms != 141: fail(f'expected 141 forms, got {total_forms}')

# ---- emit ----
L = []
L.append('// Generated by gen_schema.py from the PTO tile-macro-assembly catalog.')
L.append(f'// Catalog SHA-256: {digest}')
L.append(f'// Architecture identity: {d["architecture_identity"]}')
L.append(f'// Generated: {datetime.date.today().isoformat()} — DO NOT EDIT.')
L.append('')
L.append('namespace llvm {')
L.append('namespace LinxV5TileOpSchema {')
L.append('')
L.append(f'const char CatalogSHA256[] = "{digest}";')
L.append(f'const char ArchitectureIdentity[] = "{d["architecture_identity"]}";')
L.append(f'const unsigned OperationCount = {len(ops)};')
L.append(f'const unsigned FormCount = {total_forms};')
L.append('')

def esc(s): return s.replace('\\','\\\\').replace('"','\\"')

# Enum: operation ids in mnemonic order
L.append('// Operation ids (alphabetical by mnemonic).')
L.append('enum OperationId {')
for i, op in enumerate(sorted(ops, key=lambda o: o['mnemonic'])):
    L.append(f'  OP_{op["mnemonic"].replace(".","_").upper()} = {i},')
L.append('};')
L.append('')

# Per-form records, flattened into parallel arrays (avoids C++ initializer
# lists of aggregates that are painful in .inc files).
# We emit: forms table with indices into string/field pools.
# (records are collected first; string pool built via sid())

# Two-pass: collect records first.
records = []  # (mnemonic, form_spelling, config[], sources[], dests[], header, cfg_bindings, operand_cmds)
for op in sorted(ops, key=lambda o: o['mnemonic']):
    forms = op.get('forms') or [None]
    for f in forms:
        base = f if f else op
        exp = base.get('expansion', {})
        records.append({
            'mnemonic': op['mnemonic'],
            'spelling': base.get('spelling') or op['mnemonic'],
            'config': base.get('configuration', []),
            'sources': base.get('sources', []),
            'dests': base.get('destinations', []),
            'expansion': exp,
        })

# Build pools and tables
strs = []
def sid(s):
    if s is None: return -1
    if s not in strpool: strpool[s] = len(strs); strs.append(s)
    return strpool[s]
strpool = {}

cfg_fields = []   # FieldSlot entries
srcdst_entries = []
form_table = []
cmd_slots = []

def emit_binding(item):
    """Emit one operand/config slot record; returns index."""
    idx = {}
    return None

# For the .inc we keep it simpler: emit one struct array with inline small vectors
# is not possible in .inc; instead emit flat arrays + counts.
# FieldSlot: {FieldStr, BindingKind, ConfigKind(enum), ValueStyle(enum), Optional, DefaultStr, ConditionStr, SyntaxStr}
enum_bk = {'bundle-configuration':0,'scalar-binding':1,'tile-source-binding':2,
 'tile-destination-binding':3,'shared-tile-binding':4,'predicate-tile-source':5,
 'predicate-tile-destination':6,'predicate-cell-source':7,'predicate-cell-destination':8,
 'predicate-gpr-source':9,'predicate-gpr-destination':10}
enum_ck = {'attribute':0,'dimension':1}
enum_vs = {'bare-value':0,'named-role':1,'None':2}

def field_entry(item, section):
    return {
        'field': sid(item['field']),
        'syntax': sid(item.get('syntax')),
        'bk': enum_bk[item['binding_kind']],
        'ck': enum_ck.get(item.get('configuration_kind') or 'None', 2) if item.get('configuration_kind') else 2,
        'vs': enum_vs.get(item.get('value_style') or 'None', 2),
        'optional': 1 if item.get('optional') else 0,
        'default': sid(item.get('default')),
        'condition': sid(item.get('condition')),
        'constraint': sid(item.get('constraint')),
        'section': section,  # 0=config 1=source 2=dest
    }

all_field_entries = []
form_records = []
for r in records:
    cfg_idx = len(all_field_entries)
    for item in r['config']:
        all_field_entries.append(field_entry(item, 0))
    src_idx = len(all_field_entries)
    for item in r['sources']:
        all_field_entries.append(field_entry(item, 1))
    dst_idx = len(all_field_entries)
    for item in r['dests']:
        all_field_entries.append(field_entry(item, 2))
    exp = r['expansion']
    hdr = exp.get('header', {})
    form_records.append({
        'mnemonic': sid(r['mnemonic']),
        'spelling': sid(r['spelling']),
        'cfg_off': cfg_idx, 'cfg_n': len(r['config']),
        'src_off': src_idx, 'src_n': len(r['sources']),
        'dst_off': dst_idx, 'dst_n': len(r['dests']),
        'header_command': sid(hdr.get('command')),
        'header_selector': sid(hdr.get('selector')),
        'fold_unique': 1 if exp.get('fold',{}).get('unique_without_runtime_state') else 0,
    })

# Reorder strings pool (we built with sid during records; strs list holds order)
L = []
L.append('// Generated by gen_schema.py from the PTO tile-macro-assembly catalog.')
L.append(f'// Catalog SHA-256: {digest}')
L.append(f'// Architecture identity: {d["architecture_identity"]}')
L.append(f'// Generated: {datetime.date.today().isoformat()} - DO NOT EDIT.')
L.append('')
L.append('namespace llvm {')
L.append('namespace LinxV5TileOpSchema {')
L.append('')
L.append(f'const char CatalogSHA256[] = "{digest}";')
L.append(f'const char ArchitectureIdentity[] = "{d["architecture_identity"]}";')
L.append(f'const unsigned OperationCount = {len(ops)};')
L.append(f'const unsigned FormCount = {len(form_records)};')
L.append('')
L.append('const char *const Strings[] = {')
for s in strs:
    L.append(f'  "{esc(s)}",')
L.append('};')
L.append(f'const unsigned StringCount = {len(strs)};')
L.append('')
L.append('const FieldSlot FieldSlots[] = {')
for e in all_field_entries:
    L.append(f'  {{{e["field"]},{e["syntax"]},{e["bk"]},{e["ck"]},{e["vs"]},{e["optional"]},{e["section"]},{e["default"]},{e["condition"]},{e["constraint"]}}},')
L.append('};')
L.append('')
L.append('struct FormRecord { int16_t Mnemonic, Spelling, HeaderCommand, HeaderSelector; uint16_t CfgOff, CfgN, SrcOff, SrcN, DstOff, DstN; uint8_t FoldUnique; };')
L.append('const FormRecord Forms[] = {')
for fr in form_records:
    L.append(f'  {{{fr["mnemonic"]},{fr["spelling"]},{fr["header_command"]},{fr["header_selector"]},{fr["cfg_off"]},{fr["cfg_n"]},{fr["src_off"]},{fr["src_n"]},{fr["dst_off"]},{fr["dst_n"]},{fr["fold_unique"]}}},')
L.append('};')
L.append('')
L.append('} // namespace LinxV5TileOpSchema')
L.append('} // namespace llvm')

open(OUT,'w').write('\n'.join(L)+'\n')
print(f'OK: {len(form_records)} forms, {len(all_field_entries)} field slots, {len(strs)} strings, digest {digest[:12]}')
