#ifndef LLVM_LIB_TARGET_LINXV5_LINXV5SUBTARGET_H
#define LLVM_LIB_TARGET_LINXV5_LINXV5SUBTARGET_H

#include "LinxV5FrameLowering.h"
#include "LinxV5ISelLowering.h"
#include "LinxV5InstrInfo.h"
#include "MCTargetDesc/LinxV5BaseInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "LinxV5GenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class LinxV5Subtarget : public LinxV5GenSubtargetInfo {
  virtual void anchor();
  bool IsGeneric = true;
  bool IsSIMT = false;
  bool Has64 = true;
  bool EnableLinkerRelax = true;
  unsigned XLen = 64;
  MVT XLenVT = MVT::i64;
  LinxV5ABI::ABI TargetABI = LinxV5ABI::ABI_Unknown;
  BitVector UserReservedRegister;
  LinxV5FrameLowering FrameLowering;
  LinxV5InstrInfo InstrInfo;
  LinxV5RegisterInfo RegInfo;
  LinxV5TargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;

  /// Initializes using the passed in CPU and feature strings so that we can
  /// use initializer lists for subtarget initialization.
  LinxV5Subtarget &initializeSubtargetDependencies(const Triple &TT,
                                                   StringRef CPU,
                                                   StringRef TuneCPU,
                                                   StringRef FS,
                                                   StringRef ABIName);

public:
  // Initializes the data members to match that of the specified triple.
  LinxV5Subtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                  StringRef FS, StringRef ABIName, const TargetMachine &TM);

  virtual ~LinxV5Subtarget() = default;

  // Parses features string setting specified subtarget options. The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const LinxV5FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const LinxV5InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const LinxV5RegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }
  const LinxV5TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  bool enableMachineScheduler() const override { return true; }
  bool isScalar() const { return IsGeneric; }
  bool isGeneric() const { return IsGeneric; }
  bool isWireless() const { return false; }
  bool isSIMT() const { return IsSIMT; }
  bool enableLegacyISel() const;
  bool hasFloat() const;
  bool hasCSel() const;
  bool enableFoldCmpArith() const;
  bool enableLinkerRelax() const { return EnableLinkerRelax; }
  bool enableContinuousMemOpt() const;
  MVT getXLenVT() const { return XLenVT; }
  unsigned getXLen() const { return XLen; }
  unsigned getLaneNum() const { return 64; }
  LinxV5ABI::ABI getTargetABI() const { return TargetABI; }
  bool isRegisterReservedByUser(Register i) const {
    assert(i < LinxV5::NUM_TARGET_REGS && "Register out of range");
    return UserReservedRegister[i];
  }
};
} // namespace llvm

#endif
