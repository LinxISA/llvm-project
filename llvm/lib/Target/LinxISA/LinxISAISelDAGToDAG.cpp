static int64_t getMemScaleForVT(MVT MemVT) {
  if (MemVT == MVT::i8)
    return 1;
  if (MemVT == MVT::i16)
    return 2;
  if (MemVT == MVT::i32)
    return 4;
  if (MemVT == MVT::f32)
    return 4;
  if (MemVT == MVT::i64)
    return 8;
  if (MemVT == MVT::f64)
    return 8;
  return 1;
}

static bool isStrictTileTSize(uint64_t TSize) {
  return TSize >= 1 && TSize <= 7;
}

static uint64_t tSizeToBytes(uint64_t TSize) { return 1ull << (TSize + 6u); }

static uint64_t dtypeElementBitsForTileCheck(uint64_t DType) {
  switch (DType & 0x1fu) {
  case 0:  // FP64
  case 16: // INT64
  case 24: // UINT64
    return 64u;
  case 1:  // FP32
  case 17: // INT32
  case 25: // UINT32
    return 32u;
  case 2:  // FP16
  case 6:  // BF16
  case 18: // INT16
  case 26: // UINT16
    return 16u;
  case 3:  // FP8
  case 7:  // FPL8
  case 19: // INT8
  case 27: // UINT8
    return 8u;
  case 11: // FP4
  case 12: // FPL4
  case 20: // INT4
  case 28: // UINT4
    return 4u;
  default:
    // Keep bring-up compatibility for unknown dtype encodings and apply a
    // conservative 32-bit element width for strict byte-budget checks.
    return 32u;
  }
}

static uint64_t requirePositiveDim(int64_t Dim, StringRef IntrinsicName,
                                   StringRef DimName) {
  if (Dim <= 0) {
    report_fatal_error(Twine("Linx: ") + IntrinsicName + " requires " +
                       DimName + " > 0 for tile-byte validation (got " +
                       Twine(Dim) + ")");
  }
  return static_cast<uint64_t>(Dim);
}

static uint64_t computeTileBytesOrDie(StringRef IntrinsicName, uint64_t Dim0,
                                      uint64_t Dim1, uint64_t Dim2,
                                      uint64_t ElemBits) {
  auto MulOverflowU64 = [](uint64_t A, uint64_t B, uint64_t &Out) {
    if (A == 0 || B == 0) {
      Out = 0;
      return false;
    }
    if (A > (std::numeric_limits<uint64_t>::max() / B))
      return true;
    Out = A * B;
    return false;
  };

  uint64_t ElemCount = 0;
  uint64_t Tmp = 0;
  if (MulOverflowU64(Dim0, Dim1, Tmp) || MulOverflowU64(Tmp, Dim2, ElemCount) ||
      MulOverflowU64(ElemCount, ElemBits, Tmp)) {
    report_fatal_error(Twine("Linx: ") + IntrinsicName +
                       " tile-byte check overflow while evaluating "
                       "dim0*dim1*dim2*elem_bits");
  }
  if (Tmp > std::numeric_limits<uint64_t>::max() - 7u) {
    report_fatal_error(
        Twine("Linx: ") + IntrinsicName +
        " tile-byte check overflow while rounding bits to bytes");
  }
  return (Tmp + 7u) / 8u;
}

static void validateTileByteBudget(StringRef IntrinsicName, uint64_t Dim0,
                                   uint64_t Dim1, uint64_t Dim2,
                                   uint64_t ElemBits,
                                   std::optional<uint64_t> TSize) {
  const uint64_t Bytes =
      computeTileBytesOrDie(IntrinsicName, Dim0, Dim1, Dim2, ElemBits);
  constexpr uint64_t StrictMaxBytes = 8192u;

  if (Bytes > StrictMaxBytes) {
    report_fatal_error(Twine("Linx: ") + IntrinsicName +
                       " tile-byte check failed: bytes=" + Twine(Bytes) +
                       "B (dim0=" + Twine(Dim0) + ", dim1=" + Twine(Dim1) +
                       ", dim2=" + Twine(Dim2) +
                       ", elem_bits=" + Twine(ElemBits) +
                       ") exceeds strict max 8192B. Shrink dimensions or "
                       "element width.");
  }

  if (TSize) {
    const uint64_t LimitBytes = tSizeToBytes(*TSize);
    if (Bytes > LimitBytes) {
      report_fatal_error(Twine("Linx: ") + IntrinsicName +
                         " tile-byte check failed: bytes=" + Twine(Bytes) +
                         "B (dim0=" + Twine(Dim0) + ", dim1=" + Twine(Dim1) +
                         ", dim2=" + Twine(Dim2) + ", elem_bits=" +
                         Twine(ElemBits) + ") exceeds descriptor limit " +
                         Twine(LimitBytes) + "B (TSize=" + Twine(*TSize) +
                         "). Shrink dimensions/element width or increase "
                         "TSize.");
    }
  }
}

