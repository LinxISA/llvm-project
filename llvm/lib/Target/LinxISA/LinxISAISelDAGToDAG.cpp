static int64_t getMemScaleForVT(MVT MemVT) {
  if (MemVT == MVT::i8)
    return 1;
  if (MemVT == MVT::i16)
    return 2;
  if (MemVT == MVT::i32)
    return 4;
  if (MemVT == MVT::f32)
    return 4;
  if (MemVT == MVT::i64)
    return 8;
  if (MemVT == MVT::f64)
    return 8;
  return 1;
}

bool LinxISADAGToDAGISel::selectMemAddr(SDValue Addr, SDValue &Base,
                                       SDValue &Off, int64_t Scale) {
  SDLoc DL(Addr);
  EVT PtrVT = Addr.getValueType();

  // Fold (base + imm) into [base, imm/Scale] when possible.
  if (Addr.getOpcode() == ISD::ADD) {
    if (auto *CN = dyn_cast<ConstantSDNode>(Addr.getOperand(1))) {
      int64_t OffBytes = CN->getSExtValue();
      if (Scale != 0 && (OffBytes % Scale) == 0) {
        int64_t Scaled = OffBytes / Scale;
        if (isInt<12>(Scaled)) {
          Base = Addr.getOperand(0);
          if (auto *FIN = dyn_cast<FrameIndexSDNode>(Base.getNode()))
            Base = CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
          Off = CurDAG->getTargetConstant(Scaled, DL, MVT::i64);
          return true;
        }
      }
    }
  }

  // Frame indices are expected to be eliminated by eliminateFrameIndex().
  if (auto *FIN = dyn_cast<FrameIndexSDNode>(Addr)) {
    Base = CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
    Off = CurDAG->getTargetConstant(0, DL, MVT::i64);
    return true;
  }

  Base = Addr;
  Off = CurDAG->getTargetConstant(0, DL, MVT::i64);
  return true;
}

bool LinxISADAGToDAGISel::selectMemAddrRegOffset(SDValue Addr, SDValue &Base,
                                                 SDValue &Index,
                                                 unsigned &Shift) {
  if (Addr.getOpcode() != ISD::ADD)
    return false;

  SDLoc DL(Addr);
  EVT PtrVT = Addr.getValueType();

  auto isConst = [&](SDValue V) -> bool { return isa<ConstantSDNode>(V); };

  auto asBase = [&](SDValue V) -> SDValue {
    if (auto *FIN = dyn_cast<FrameIndexSDNode>(V.getNode()))
      return CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
    return V;
  };

  auto matchIndexAndShift = [&](SDValue V, SDValue &OutIdx,
                                unsigned &OutShift) -> bool {
    auto isNeverIndex = [&](SDValue X) -> bool {
      SDNode *N = X.getNode();
      if (!N)
        return false;
      // Don't treat PC-relative address materialization as an index term.
      // This avoids selecting addresses like (idx + ADDTPC(symbol)) as
      // [idx, ADDTPC(symbol)] which would swap base/index for reg-offset loads.
      if (N->isMachineOpcode()) {
        unsigned Opc = N->getMachineOpcode();
        if (Opc == LinxISA::ADDTPC || Opc == LinxISA::LUI ||
            Opc == LinxISA::HLLUI)
          return true;
        return false;
      }

      switch (N->getOpcode()) {
      case ISD::GlobalAddress:
      case ISD::ExternalSymbol:
      case ISD::TargetGlobalAddress:
      case ISD::TargetExternalSymbol:
      case ISD::TargetConstantPool:
      case ISD::TargetJumpTable:
      case ISD::TargetBlockAddress:
        return true;
      default:
        break;
      }
      return false;
    };

    // base + (idx << shamt)
    if (V.getOpcode() == ISD::SHL) {
      if (auto *CN = dyn_cast<ConstantSDNode>(V.getOperand(1))) {
        uint64_t S = CN->getZExtValue();
        if (S >= 32)
          return false;
        OutIdx = V.getOperand(0);
        OutShift = static_cast<unsigned>(S);
        if (isNeverIndex(OutIdx))
          return false;
        if (isa<ConstantSDNode>(OutIdx))
          return false;
        return true;
      }
    }

    // base + idx (shamt=0)
    if (isa<ConstantSDNode>(V))
      return false;
    if (isNeverIndex(V))
      return false;
    OutIdx = V;
    OutShift = 0;
    return true;
  };

  SDValue A = Addr.getOperand(0);
  SDValue B = Addr.getOperand(1);

  // Prefer matching the RHS as the index term for canonical addresses.
  if (!isConst(A) && matchIndexAndShift(B, Index, Shift)) {
    Base = asBase(A);
    return true;
  }
  if (!isConst(B) && matchIndexAndShift(A, Index, Shift)) {
    Base = asBase(B);
    return true;
  }

  (void)DL;
  return false;
}

bool LinxISADAGToDAGISel::selectPcrSymbolAddr(SDValue Addr, SDValue &Sym) {
  SDLoc DL(Addr);
  EVT PtrVT = Addr.getValueType();

  auto isSameSymbolRef = [&](SDValue A, SDValue B) -> bool {
    if (A.getNode() == B.getNode())
      return true;

    auto asGA = [](SDValue V) -> GlobalAddressSDNode * {
      return dyn_cast<GlobalAddressSDNode>(V.getNode());
    };
    auto asCP = [](SDValue V) -> ConstantPoolSDNode * {
      return dyn_cast<ConstantPoolSDNode>(V.getNode());
    };

    if (auto *GAa = asGA(A)) {
      if (auto *GAb = asGA(B)) {
        return GAa->getGlobal() == GAb->getGlobal() &&
               GAa->getOffset() == GAb->getOffset();
      }
    }
    if (auto *CPa = asCP(A)) {
      if (auto *CPb = asCP(B)) {
        return CPa->getConstVal() == CPb->getConstVal() &&
               CPa->getOffset() == CPb->getOffset() &&
               CPa->getAlign() == CPb->getAlign();
      }
    }
    return false;
  };

  auto tryMatchMaterialized = [&](SDValue V) -> std::optional<SDValue> {
    auto *MN = dyn_cast<MachineSDNode>(V.getNode());
    if (!MN)
      return std::nullopt;

    const unsigned Opc = MN->getMachineOpcode();
    if (Opc != LinxISA::ADDIri && Opc != LinxISA::ADDIWri)
      return std::nullopt;

    if (MN->getNumOperands() < 2)
      return std::nullopt;

    SDValue Page = MN->getOperand(0);
    SDValue GA = MN->getOperand(1);

    auto *PageMN = dyn_cast<MachineSDNode>(Page.getNode());
    if (!PageMN || PageMN->getMachineOpcode() != LinxISA::ADDTPC ||
        PageMN->getNumOperands() < 1)
      return std::nullopt;

    // Allow equivalent (but not pointer-identical) symbol refs. Different
    // lowering paths may recreate the target symbol node.
    if (!isSameSymbolRef(PageMN->getOperand(0), GA))
      return std::nullopt;

    return GA;
  };

  auto adjustAddend = [&](SDValue GA, int64_t AddBytes) -> SDValue {
    if (AddBytes == 0)
      return GA;
    if (auto *G = dyn_cast<GlobalAddressSDNode>(GA.getNode())) {
      const GlobalValue *GV = G->getGlobal();
      const int64_t Off = G->getOffset() + AddBytes;
      return CurDAG->getTargetGlobalAddress(GV, DL, PtrVT, Off);
    }
    if (auto *CP = dyn_cast<ConstantPoolSDNode>(GA.getNode())) {
      const int64_t Off = CP->getOffset() + AddBytes;
      return CurDAG->getTargetConstantPool(CP->getConstVal(), PtrVT, CP->getAlign(),
                                           Off);
    }
    return SDValue();
  };

  if (auto GA = tryMatchMaterialized(Addr)) {
    Sym = *GA;
    return true;
  }

  if (Addr.getOpcode() == ISD::ADD) {
    if (auto *CN = dyn_cast<ConstantSDNode>(Addr.getOperand(1))) {
      if (auto GA = tryMatchMaterialized(Addr.getOperand(0))) {
        SDValue Adj = adjustAddend(*GA, CN->getSExtValue());
        if (Adj.getNode()) {
          Sym = Adj;
          return true;
        }
      }
    }
    if (auto *CN = dyn_cast<ConstantSDNode>(Addr.getOperand(0))) {
      if (auto GA = tryMatchMaterialized(Addr.getOperand(1))) {
        SDValue Adj = adjustAddend(*GA, CN->getSExtValue());
        if (Adj.getNode()) {
          Sym = Adj;
          return true;
        }
      }
    }
  }

  return false;
}

static unsigned selectBrOpcode(ISD::CondCode CC, bool &SwapOps) {
  SwapOps = false;
  switch (CC) {
  case ISD::SETEQ:
    return LinxISA::BEQ;
  case ISD::SETNE:
    return LinxISA::BNE;
  case ISD::SETLT:
    return LinxISA::BLT;
  case ISD::SETLE:
    SwapOps = true;
    return LinxISA::BGE;
  case ISD::SETGT:
    SwapOps = true;
    return LinxISA::BLT;
  case ISD::SETGE:
    return LinxISA::BGE;
  case ISD::SETULT:
    return LinxISA::BLTU;
  case ISD::SETULE:
    SwapOps = true;
    return LinxISA::BGEU;
  case ISD::SETUGT:
    SwapOps = true;
    return LinxISA::BLTU;
  case ISD::SETUGE:
    return LinxISA::BGEU;
  default:
    llvm_unreachable("Unsupported Linx branch condition");
  }
}

static unsigned selectSetCCOpcode(ISD::CondCode CC, bool &SwapOps) {
  SwapOps = false;
  switch (CC) {
  case ISD::SETEQ:
    return LinxISA::CMPEQ;
  case ISD::SETNE:
    return LinxISA::CMPNE;
  case ISD::SETLT:
    return LinxISA::CMPLT;
  case ISD::SETLE:
    SwapOps = true;
    return LinxISA::CMPGE;
  case ISD::SETGT:
    SwapOps = true;
    return LinxISA::CMPLT;
  case ISD::SETGE:
    return LinxISA::CMPGE;
  case ISD::SETULT:
    return LinxISA::CMPLTU;
  case ISD::SETULE:
    SwapOps = true;
    return LinxISA::CMPGEU;
  case ISD::SETUGT:
    SwapOps = true;
    return LinxISA::CMPLTU;
  case ISD::SETUGE:
    return LinxISA::CMPGEU;
  default:
    llvm_unreachable("Unsupported Linx setcc condition");
  }
}

void LinxISADAGToDAGISel::Select(SDNode *N) {
  unsigned Opcode = N->getOpcode();

  if (N->isMachineOpcode())
    return;

  switch (Opcode) {
  default:
    break;

  case ISD::ADD:
  case ISD::SUB: {
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    if (VT == MVT::v1024i32) {
      SDValue A = N->getOperand(0);
      SDValue B = N->getOperand(1);
      const unsigned PseudoOpc =
          (Opcode == ISD::ADD) ? LinxISA::PSEUDO_VTILE_ADD
                               : LinxISA::PSEUDO_VTILE_SUB;
      ReplaceNode(N, CurDAG->getMachineNode(PseudoOpc, DL, VT, A, B));
      return;
    }
    break;
  }

  case ISD::BITCAST: {
    // LinxISA uses a unified reg5 register file for integers and scalars.
    // Treat scalar i32/i64/f32/f64 bitcasts as a no-op and select them to a
    // COPY to change the SelectionDAG value type.
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    SDValue Src = N->getOperand(0);
    EVT SrcVT = Src.getValueType();

    auto IsScalarGPRVT = [](EVT T) {
      return T == MVT::i32 || T == MVT::i64 || T == MVT::f32 || T == MVT::f64;
    };

    if (IsScalarGPRVT(VT) && IsScalarGPRVT(SrcVT) &&
        VT.getSizeInBits() == SrcVT.getSizeInBits()) {
      ReplaceNode(N, CurDAG->getMachineNode(TargetOpcode::COPY, DL, VT, Src));
      return;
    }

    break;
  }

  case ISD::ANY_EXTEND: {
    // any_extend preserves the low bits and leaves the upper bits undefined.
    // This is a no-op on LinxISA GPRs (i32/i64 share the same register file),
    // so select to a COPY between differently-typed DAG values.
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    SDValue Src = N->getOperand(0);
    ReplaceNode(N, CurDAG->getMachineNode(TargetOpcode::COPY, DL, VT, Src));
    return;
  }

  case ISD::TRUNCATE: {
    // i64->i32 truncation is just taking the low bits, which is a no-op in the
    // GPR register file. Select to a COPY to change the DAG value type.
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    SDValue Src = N->getOperand(0);
    ReplaceNode(N, CurDAG->getMachineNode(TargetOpcode::COPY, DL, VT, Src));
    return;
  }

  case ISD::SIGN_EXTEND_INREG: {
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    SDValue Val = N->getOperand(0);
    EVT FromVT = cast<VTSDNode>(N->getOperand(1))->getVT();

    // Common case for Linx64: sign-extend low 32 bits in a GPR.
    if (VT == MVT::i64 && FromVT == MVT::i32) {
      SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i64);
      ReplaceNode(N, CurDAG->getMachineNode(LinxISA::ADDWrr, DL, VT, Val, Zero));
      return;
    }

    // Sign-extend subword values in the low 32 bits via shifts.
    if (VT == MVT::i32 &&
        (FromVT == MVT::i1 || FromVT == MVT::i8 || FromVT == MVT::i16)) {
      unsigned FromBits = FromVT.getScalarSizeInBits();
      unsigned Shift = 32 - FromBits;
      SDValue ShImm = CurDAG->getTargetConstant(Shift, DL, MVT::i32);
      SDNode *Shl = CurDAG->getMachineNode(LinxISA::SLLIWri, DL, VT, Val, ShImm);
      ReplaceNode(N, CurDAG->getMachineNode(LinxISA::SRAIWri, DL, VT,
                                            SDValue(Shl, 0), ShImm));
      return;
    }

    // Sign-extend subword values in a 64-bit GPR via reg-reg shifts (immediate
    // shifts are limited to 5-bit amounts in the current encoding).
    if (VT == MVT::i64 &&
        (FromVT == MVT::i1 || FromVT == MVT::i8 || FromVT == MVT::i16)) {
      unsigned FromBits = FromVT.getScalarSizeInBits();
      unsigned Shift = 64 - FromBits;
      SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i64);
      SDValue ShImm = CurDAG->getTargetConstant(Shift, DL, MVT::i64);
      SDNode *ShAmt =
          CurDAG->getMachineNode(LinxISA::ADDIri, DL, MVT::i64, Zero, ShImm);
      SDNode *Shl = CurDAG->getMachineNode(LinxISA::SLLrr, DL, VT, Val,
                                           SDValue(ShAmt, 0));
      ReplaceNode(N, CurDAG->getMachineNode(LinxISA::SRArr, DL, VT,
                                            SDValue(Shl, 0), SDValue(ShAmt, 0)));
      return;
    }

    break;
  }

  case ISD::FrameIndex: {
    auto *FIN = cast<FrameIndexSDNode>(N);
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    SDValue TFI = CurDAG->getTargetFrameIndex(FIN->getIndex(), VT);
    SDValue ZeroImm = CurDAG->getTargetConstant(0, DL, MVT::i64);
    ReplaceNode(N, CurDAG->getMachineNode(LinxISA::ADDIri, DL, VT, TFI, ZeroImm));
    return;
  }

  case ISD::INTRINSIC_W_CHAIN: {
    auto *C = dyn_cast<ConstantSDNode>(N->getOperand(1));
    if (!C)
      break;

    const unsigned IntrID = C->getZExtValue();
    SDLoc DL(N);

    if (IntrID == Intrinsic::linx_tma_tload) {
      // (chain, id, base, immSizeCode)
      auto *SizeC = dyn_cast<ConstantSDNode>(N->getOperand(3));
      if (!SizeC)
        report_fatal_error("Linx: tma.tload requires constant SizeCode");

      SDValue Chain = N->getOperand(0);
      SDValue Base = N->getOperand(2);
      SDValue SizeImm =
          CurDAG->getTargetConstant(SizeC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {Base, SizeImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_TMA_TLOAD, DL,
                                           MVT::v1024i32, MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_tma_tload_desc) {
      // (chain, id, base, immLayout, immLB0, immLB1, immLB2, immSizeCode)
      auto *LayoutC = dyn_cast<ConstantSDNode>(N->getOperand(3));
      auto *LB0C = dyn_cast<ConstantSDNode>(N->getOperand(4));
      auto *LB1C = dyn_cast<ConstantSDNode>(N->getOperand(5));
      auto *LB2C = dyn_cast<ConstantSDNode>(N->getOperand(6));
      auto *SizeC = dyn_cast<ConstantSDNode>(N->getOperand(7));
      if (!LayoutC || !LB0C || !LB1C || !LB2C || !SizeC)
        report_fatal_error("Linx: tma.tload.desc requires constant layout/lb0/lb1/lb2/size");

      SDValue Chain = N->getOperand(0);
      SDValue Base = N->getOperand(2);
      SDValue LayoutImm =
          CurDAG->getTargetConstant(LayoutC->getZExtValue(), DL, MVT::i64);
      SDValue LB0Imm =
          CurDAG->getTargetConstant(LB0C->getZExtValue(), DL, MVT::i64);
      SDValue LB1Imm =
          CurDAG->getTargetConstant(LB1C->getZExtValue(), DL, MVT::i64);
      SDValue LB2Imm =
          CurDAG->getTargetConstant(LB2C->getZExtValue(), DL, MVT::i64);
      SDValue SizeImm =
          CurDAG->getTargetConstant(SizeC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {Base, LayoutImm, LB0Imm, LB1Imm, LB2Imm, SizeImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_TMA_TLOAD_DESC, DL,
                                           MVT::v1024i32, MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_cube_mamulb) {
      // (chain, id, a, b, immM, immN, immK)
      auto *MC = dyn_cast<ConstantSDNode>(N->getOperand(4));
      auto *NC = dyn_cast<ConstantSDNode>(N->getOperand(5));
      auto *KC = dyn_cast<ConstantSDNode>(N->getOperand(6));
      if (!MC || !NC || !KC)
        report_fatal_error("Linx: cube.mamulb requires constant M/N/K");

      SDValue Chain = N->getOperand(0);
      SDValue A = N->getOperand(2);
      SDValue B = N->getOperand(3);
      SDValue MImm =
          CurDAG->getTargetConstant(MC->getZExtValue(), DL, MVT::i64);
      SDValue NImm =
          CurDAG->getTargetConstant(NC->getZExtValue(), DL, MVT::i64);
      SDValue KImm =
          CurDAG->getTargetConstant(KC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {A, B, MImm, NImm, KImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_CUBE_MAMULB, DL,
                                           MVT::v1024i32, MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_cube_mamulb_acc) {
      // (chain, id, acc, a, b, immM, immN, immK)
      auto *MC = dyn_cast<ConstantSDNode>(N->getOperand(5));
      auto *NC = dyn_cast<ConstantSDNode>(N->getOperand(6));
      auto *KC = dyn_cast<ConstantSDNode>(N->getOperand(7));
      if (!MC || !NC || !KC)
        report_fatal_error("Linx: cube.mamulb.acc requires constant M/N/K");

      SDValue Chain = N->getOperand(0);
      SDValue Acc = N->getOperand(2);
      SDValue A = N->getOperand(3);
      SDValue B = N->getOperand(4);
      SDValue MImm =
          CurDAG->getTargetConstant(MC->getZExtValue(), DL, MVT::i64);
      SDValue NImm =
          CurDAG->getTargetConstant(NC->getZExtValue(), DL, MVT::i64);
      SDValue KImm =
          CurDAG->getTargetConstant(KC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {Acc, A, B, MImm, NImm, KImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_CUBE_MAMULB_ACC, DL,
                                           MVT::v1024i32, MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_vpar_tadd) {
      // (chain, id, a, b, immSizeCode)
      auto *SizeC = dyn_cast<ConstantSDNode>(N->getOperand(4));
      if (!SizeC)
        report_fatal_error("Linx: vpar.tadd requires constant SizeCode");

      SDValue Chain = N->getOperand(0);
      SDValue A = N->getOperand(2);
      SDValue B = N->getOperand(3);
      SDValue SizeImm =
          CurDAG->getTargetConstant(SizeC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {A, B, SizeImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_VPAR_TADD, DL,
                                           MVT::v1024i32, MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_vpar_tsub) {
      // (chain, id, a, b, immSizeCode)
      auto *SizeC = dyn_cast<ConstantSDNode>(N->getOperand(4));
      if (!SizeC)
        report_fatal_error("Linx: vpar.tsub requires constant SizeCode");

      SDValue Chain = N->getOperand(0);
      SDValue A = N->getOperand(2);
      SDValue B = N->getOperand(3);
      SDValue SizeImm =
          CurDAG->getTargetConstant(SizeC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {A, B, SizeImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_VPAR_TSUB, DL,
                                           MVT::v1024i32, MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    break;
  }

  case ISD::INTRINSIC_VOID: {
    auto *C = dyn_cast<ConstantSDNode>(N->getOperand(1));
    if (!C)
      break;
    const unsigned IntrID = C->getZExtValue();
    SDLoc DL(N);

    if (IntrID == Intrinsic::linx_tma_tstore) {
      // (chain, id, base, tile, immSizeCode)
      auto *SizeC = dyn_cast<ConstantSDNode>(N->getOperand(4));
      if (!SizeC)
        report_fatal_error("Linx: tma.tstore requires constant SizeCode");

      SDValue Chain = N->getOperand(0);
      SDValue Base = N->getOperand(2);
      SDValue Tile = N->getOperand(3);
      SDValue SizeImm =
          CurDAG->getTargetConstant(SizeC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {Base, Tile, SizeImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_TMA_TSTORE, DL,
                                           MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_tma_tstore_desc) {
      // (chain, id, base, tile, immLayout, immLB0, immLB1, immLB2, immSizeCode)
      auto *LayoutC = dyn_cast<ConstantSDNode>(N->getOperand(4));
      auto *LB0C = dyn_cast<ConstantSDNode>(N->getOperand(5));
      auto *LB1C = dyn_cast<ConstantSDNode>(N->getOperand(6));
      auto *LB2C = dyn_cast<ConstantSDNode>(N->getOperand(7));
      auto *SizeC = dyn_cast<ConstantSDNode>(N->getOperand(8));
      if (!LayoutC || !LB0C || !LB1C || !LB2C || !SizeC)
        report_fatal_error("Linx: tma.tstore.desc requires constant layout/lb0/lb1/lb2/size");

      SDValue Chain = N->getOperand(0);
      SDValue Base = N->getOperand(2);
      SDValue Tile = N->getOperand(3);
      SDValue LayoutImm =
          CurDAG->getTargetConstant(LayoutC->getZExtValue(), DL, MVT::i64);
      SDValue LB0Imm =
          CurDAG->getTargetConstant(LB0C->getZExtValue(), DL, MVT::i64);
      SDValue LB1Imm =
          CurDAG->getTargetConstant(LB1C->getZExtValue(), DL, MVT::i64);
      SDValue LB2Imm =
          CurDAG->getTargetConstant(LB2C->getZExtValue(), DL, MVT::i64);
      SDValue SizeImm =
          CurDAG->getTargetConstant(SizeC->getZExtValue(), DL, MVT::i64);
      SDValue Ops[] = {Base, Tile, LayoutImm, LB0Imm, LB1Imm, LB2Imm, SizeImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_TMA_TSTORE_DESC, DL,
                                           MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    if (IntrID == Intrinsic::linx_vblock_launch) {
      // (chain, id, vkind, body_sym, dim0, dim1, dim2, attr_bits)
      auto *VKindC = dyn_cast<ConstantSDNode>(N->getOperand(2));
      auto *Dim0C = dyn_cast<ConstantSDNode>(N->getOperand(4));
      auto *Dim1C = dyn_cast<ConstantSDNode>(N->getOperand(5));
      auto *Dim2C = dyn_cast<ConstantSDNode>(N->getOperand(6));
      auto *AttrC = dyn_cast<ConstantSDNode>(N->getOperand(7));
      if (!VKindC || !Dim0C || !Dim1C || !Dim2C || !AttrC)
        report_fatal_error("Linx: vblock.launch requires constant args for now");

      SDValue Chain = N->getOperand(0);
      SDValue VKindImm =
          CurDAG->getTargetConstant(VKindC->getZExtValue(), DL, MVT::i64);
      SDValue Dim0Imm =
          CurDAG->getTargetConstant(Dim0C->getZExtValue(), DL, MVT::i64);
      SDValue Dim1Imm =
          CurDAG->getTargetConstant(Dim1C->getZExtValue(), DL, MVT::i64);
      SDValue Dim2Imm =
          CurDAG->getTargetConstant(Dim2C->getZExtValue(), DL, MVT::i64);
      SDValue AttrImm =
          CurDAG->getTargetConstant(AttrC->getZExtValue(), DL, MVT::i64);

      SDValue Ops[] = {VKindImm, Dim0Imm, Dim1Imm, Dim2Imm, AttrImm, Chain};
      SDNode *Res = CurDAG->getMachineNode(LinxISA::PSEUDO_VBLOCK_LAUNCH, DL,
                                           MVT::Other, Ops);
      ReplaceNode(N, Res);
      return;
    }

    break;
  }

  case ISD::SHL:
  case ISD::SRL:
  case ISD::SRA: {
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    SDValue Val = N->getOperand(0);
    SDValue Sh = N->getOperand(1);

    if (auto *CN = dyn_cast<ConstantSDNode>(Sh)) {
      uint64_t ShAmt = CN->getZExtValue();
      if (VT == MVT::i64 && isUInt<5>(ShAmt)) {
        unsigned Opc = 0;
        if (Opcode == ISD::SHL)
          Opc = LinxISA::SLLIri;
        else if (Opcode == ISD::SRL)
          Opc = LinxISA::SRLIri;
        else
          Opc = LinxISA::SRAIri;

        SDValue Imm = CurDAG->getTargetConstant(ShAmt, DL, MVT::i64);
        ReplaceNode(N, CurDAG->getMachineNode(Opc, DL, VT, Val, Imm));
        return;
      }

      if (VT == MVT::i32 && isUInt<5>(ShAmt)) {
        unsigned Opc = 0;
        if (Opcode == ISD::SHL)
          Opc = LinxISA::SLLIWri;
        else if (Opcode == ISD::SRL)
          Opc = LinxISA::SRLIWri;
        else
          Opc = LinxISA::SRAIWri;

        SDValue Imm = CurDAG->getTargetConstant(ShAmt, DL, MVT::i32);
        ReplaceNode(N, CurDAG->getMachineNode(Opc, DL, VT, Val, Imm));
        return;
      }
    }

    // Reg-reg shifts for 32-bit values: select explicitly to avoid type
    // mismatches on the shift amount (it may be i64 due to ABI lowering).
    if (VT == MVT::i32) {
      unsigned Opc = 0;
      if (Opcode == ISD::SHL)
        Opc = LinxISA::SLLWrr;
      else if (Opcode == ISD::SRL)
        Opc = LinxISA::SRLWrr;
      else
        Opc = LinxISA::SRAWrr;

      ReplaceNode(N, CurDAG->getMachineNode(Opc, DL, VT, Val, Sh));
      return;
    }

    break;
  }

  case ISD::AND:
  case ISD::OR:
  case ISD::XOR: {
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    if (VT != MVT::i32)
      break;

    SDValue LHS = N->getOperand(0);
    SDValue RHS = N->getOperand(1);

    auto *CN = dyn_cast<ConstantSDNode>(RHS);
    if (!CN) {
      // Handle commuted forms with the constant on the LHS.
      CN = dyn_cast<ConstantSDNode>(LHS);
      if (!CN)
        break;
      std::swap(LHS, RHS);
    }

    int64_t ImmVal = CN->getSExtValue();
    if (!isInt<12>(ImmVal))
      break;

    unsigned Opc = 0;
    switch (Opcode) {
    case ISD::AND:
      Opc = LinxISA::ANDIWri;
      break;
    case ISD::OR:
      Opc = LinxISA::ORIWri;
      break;
    case ISD::XOR:
      Opc = LinxISA::XORIWri;
      break;
    default:
      llvm_unreachable("Unexpected opcode");
    }

    SDValue Imm = CurDAG->getTargetConstant(ImmVal, DL, MVT::i32);
    ReplaceNode(N, CurDAG->getMachineNode(Opc, DL, VT, LHS, Imm));
    return;
  }

  case ISD::Constant: {
    auto *C = cast<ConstantSDNode>(N);
    SDLoc DL(N);
    EVT VT = N->getValueType(0);
    int64_t Val = C->getSExtValue();

    if (VT == MVT::i64) {
      const uint64_t UVal = C->getZExtValue();
      if (Val >= 0 && isUInt<12>(Val)) {
        SDValue Imm = CurDAG->getTargetConstant(Val, DL, MVT::i64);
        SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i64);
        ReplaceNode(N, CurDAG->getMachineNode(LinxISA::ADDIri, DL, VT, Zero, Imm));
        return;
      }
      if (Val < 0 && isUInt<12>(-Val)) {
        SDValue Imm = CurDAG->getTargetConstant(-Val, DL, MVT::i64);
        SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i64);
        ReplaceNode(N, CurDAG->getMachineNode(LinxISA::SUBIri, DL, VT, Zero, Imm));
        return;
      }

      // Prefer LUI for 4KiB-aligned values representable by a signed imm20.
      // This emits a real 32-bit instruction (LUI) instead of the wider HL.LUI.
      if (isInt<32>(Val) && (Val & 0xfff) == 0) {
        int64_t Upper = Val >> 12;
        if (isInt<20>(Upper)) {
          SDValue Imm = CurDAG->getTargetConstant(Upper, DL, MVT::i64);
          ReplaceNode(N, CurDAG->getMachineNode(LinxISA::LUI, DL, VT, Imm));
          return;
        }
      }

      if (isInt<32>(Val)) {
        SDValue Imm = CurDAG->getTargetConstant(Val, DL, MVT::i64);
        ReplaceNode(N, CurDAG->getMachineNode(LinxISA::HLLUI, DL, VT, Imm));
        return;
      }

      if (isUInt<32>(Val)) {
        // Materialize the same 32-bit bit-pattern as a sign-extended value,
        // then clear the upper 32 bits.
        SDValue Imm = CurDAG->getTargetConstant(
            static_cast<int32_t>(static_cast<uint32_t>(Val)), DL, MVT::i64);
        SDValue Res =
            SDValue(CurDAG->getMachineNode(LinxISA::HLLUI, DL, MVT::i64, Imm), 0);

        SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i64);
        SDValue ShImm = CurDAG->getTargetConstant(32, DL, MVT::i64);
        SDValue ShAmt = SDValue(
            CurDAG->getMachineNode(LinxISA::ADDIri, DL, MVT::i64, Zero, ShImm),
            0);

        SDValue Shl = SDValue(
            CurDAG->getMachineNode(LinxISA::SLLrr, DL, MVT::i64, Res, ShAmt), 0);
        SDValue Shr = SDValue(
            CurDAG->getMachineNode(LinxISA::SRLrr, DL, MVT::i64, Shl, ShAmt), 0);
        ReplaceNode(N, Shr.getNode());
        return;
      }

      // Generic 64-bit materialization: build from high/low 32-bit halves.
      //
      //   hi = sext_i64((int32_t)(UVal >> 32))
      //   lo = zext_i64((uint32_t)UVal)
      //   res = (hi << 32) | lo
      //
      // This avoids the bring-up fatal error for i64 constants used in tests
      // and allows the backend to select legal i64 materializations without
      // requiring HL.* immediate arithmetic instructions.
      uint32_t Hi32 = static_cast<uint32_t>(UVal >> 32);
      uint32_t Lo32 = static_cast<uint32_t>(UVal & 0xffffffffu);

      SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i64);
      SDValue ShImm32 = CurDAG->getTargetConstant(32, DL, MVT::i64);
      SDValue ShAmt32 =
          SDValue(CurDAG->getMachineNode(LinxISA::ADDIri, DL, MVT::i64, Zero,
                                         ShImm32),
                  0);

      // Load hi32 (sign-extended) and shift it into the upper 32 bits.
      SDValue HiImm = CurDAG->getTargetConstant(
          static_cast<int64_t>(static_cast<int32_t>(Hi32)), DL, MVT::i64);
      SDValue Hi =
          SDValue(CurDAG->getMachineNode(LinxISA::HLLUI, DL, MVT::i64, HiImm),
                  0);
      SDValue HiShifted =
          SDValue(CurDAG->getMachineNode(LinxISA::SLLrr, DL, MVT::i64, Hi,
                                         ShAmt32),
                  0);

      // Load lo32 and clear the upper 32 bits to obtain a zero-extended i64.
      SDValue LoImm = CurDAG->getTargetConstant(
          static_cast<int64_t>(static_cast<int32_t>(Lo32)), DL, MVT::i64);
      SDValue Lo =
          SDValue(CurDAG->getMachineNode(LinxISA::HLLUI, DL, MVT::i64, LoImm),
                  0);
      SDValue LoShl = SDValue(
          CurDAG->getMachineNode(LinxISA::SLLrr, DL, MVT::i64, Lo, ShAmt32), 0);
      SDValue LoZext = SDValue(CurDAG->getMachineNode(LinxISA::SRLrr, DL,
                                                      MVT::i64, LoShl, ShAmt32),
                               0);

      SDValue Res = SDValue(CurDAG->getMachineNode(LinxISA::ORrr, DL, MVT::i64,
                                                   HiShifted, LoZext),
                            0);
      ReplaceNode(N, Res.getNode());
      return;
    } else if (VT == MVT::i32) {
      if (Val >= 0 && isUInt<12>(Val)) {
        SDValue Imm = CurDAG->getTargetConstant(Val, DL, MVT::i32);
        SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i32);
        ReplaceNode(N, CurDAG->getMachineNode(LinxISA::ADDIWri, DL, VT, Zero, Imm));
        return;
      }
      if (Val < 0 && isUInt<12>(-Val)) {
        SDValue Imm = CurDAG->getTargetConstant(-Val, DL, MVT::i32);
        SDValue Zero = CurDAG->getRegister(LinxISA::R0, MVT::i32);
        ReplaceNode(N, CurDAG->getMachineNode(LinxISA::SUBIWri, DL, VT, Zero, Imm));
        return;
      }

      // Prefer LUI for 4KiB-aligned values representable by a signed imm20.
      if (isInt<32>(Val) && (Val & 0xfff) == 0) {
        int64_t Upper = Val >> 12;
        if (isInt<20>(Upper)) {
          SDValue Imm = CurDAG->getTargetConstant(Upper, DL, MVT::i64);
          ReplaceNode(N, CurDAG->getMachineNode(LinxISA::LUI, DL, VT, Imm));
          return;
        }
      }

      // Materialize sign-extended 32-bit constants using HL.LUI.
      if (isInt<32>(Val)) {
        SDValue Imm = CurDAG->getTargetConstant(Val, DL, MVT::i64);
        ReplaceNode(N, CurDAG->getMachineNode(LinxISA::HLLUI, DL, VT, Imm));
        return;
      }
    }

    report_fatal_error("Linx: constant out of range for bring-up");
  }

  case ISD::LOAD: {
    auto *LD = cast<LoadSDNode>(N);
    if (!LD->isUnindexed())
      break;

    SDLoc DL(N);
    MVT MemVT = LD->getMemoryVT().getSimpleVT();
    int64_t Scale = getMemScaleForVT(MemVT);

    // Fold materialized PC-relative addresses back into a single *.PCR load:
    //   addr = ADDI(ADDTPC(sym), sym) [+ const]
    //   load [addr] -> *.pcr [sym+const]
    SDValue PcrSym;
	    if (selectPcrSymbolAddr(LD->getBasePtr(), PcrSym)) {
	      unsigned Opc = 0;
	      switch (MemVT.SimpleTy) {
	      case MVT::i8:
	        Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LBU_PCR
	                                                        : LinxISA::LB_PCR;
	        break;
	      case MVT::i16:
	        Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LHU_PCR
	                                                        : LinxISA::LH_PCR;
	        break;
	      case MVT::i32:
	        Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LWU_PCR
	                                                        : LinxISA::LW_PCR;
	        break;
	      case MVT::f32:
	        // Preserve the f32 bit-pattern in the low 32 bits.
	        Opc = LinxISA::LWU_PCR;
	        break;
	      case MVT::i64:
	      case MVT::f64:
	        Opc = LinxISA::LD_PCR;
	        break;
	      default:
	        Opc = 0;
	        break;
	      }

      if (Opc) {
        SDVTList VTs = CurDAG->getVTList(LD->getValueType(0), MVT::Other);
        SDValue Ops[] = {PcrSym, LD->getChain()};
        SDNode *Res = CurDAG->getMachineNode(Opc, DL, VTs, Ops);
        ReplaceNode(N, Res);
        return;
      }
    }

    // Prefer reg-offset addressing when the address matches `base + (idx<<sh)`.
    SDValue BaseRO, IndexRO;
    unsigned Shift = 0;
    if (selectMemAddrRegOffset(LD->getBasePtr(), BaseRO, IndexRO, Shift)) {
      unsigned Opc = 0;
      switch (MemVT.SimpleTy) {
      case MVT::i8:
        Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LBU
                                                        : LinxISA::LB;
        break;
      case MVT::i16:
        Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LHU
                                                        : LinxISA::LH;
        break;
      case MVT::i32:
        Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LWU
                                                        : LinxISA::LW;
        break;
      case MVT::f32:
        // Preserve the f32 bit-pattern in the low 32 bits.
        Opc = LinxISA::LWU;
        break;
      case MVT::i64:
        Opc = LinxISA::LD;
        break;
      case MVT::f64:
        Opc = LinxISA::LD;
        break;
      default:
        Opc = 0;
        break;
      }

      if (Opc) {
        SDValue ShAmt = CurDAG->getTargetConstant(Shift, DL, MVT::i64);
        SDVTList VTs = CurDAG->getVTList(LD->getValueType(0), MVT::Other);
        SDValue Ops[] = {BaseRO, IndexRO, ShAmt, LD->getChain()};
        SDNode *Res = CurDAG->getMachineNode(Opc, DL, VTs, Ops);
        ReplaceNode(N, Res);
        return;
      }
    }

    unsigned Opc = 0;
    switch (MemVT.SimpleTy) {
    case MVT::i1:
      // LLVM may represent boolean globals as i1 in memory. On LinxISA, bools
      // are stored as bytes (0/1), so select a byte load.
      Opc = LinxISA::LBUI;
      break;
    case MVT::i8:
      Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LBUI
                                                      : LinxISA::LBI;
      break;
    case MVT::i16:
      Opc = (LD->getExtensionType() == ISD::ZEXTLOAD) ? LinxISA::LHUI
                                                      : LinxISA::LHI;
      break;
    case MVT::i32:
      if (LD->getExtensionType() == ISD::ZEXTLOAD)
        Opc = LinxISA::LWUI;
      else
        Opc = LinxISA::LWI;
      break;
    case MVT::f32:
      // Preserve the f32 bit-pattern in the low 32 bits.
      Opc = LinxISA::LWUI;
      break;
    case MVT::i64:
      Opc = LinxISA::LDI;
      break;
    case MVT::f64:
      Opc = LinxISA::LDI;
      break;
    default:
      report_fatal_error("Linx: unsupported load type");
    }

    SDValue Base, Off;
    selectMemAddr(LD->getBasePtr(), Base, Off, Scale);

    SDVTList VTs = CurDAG->getVTList(LD->getValueType(0), MVT::Other);
    SDValue Ops[] = {Base, Off, LD->getChain()};
    SDNode *Res = CurDAG->getMachineNode(Opc, DL, VTs, Ops);

    ReplaceNode(N, Res);
    return;
  }

  case ISD::STORE: {
    auto *ST = cast<StoreSDNode>(N);
    if (!ST->isUnindexed())
      break;

    SDLoc DL(N);
    MVT MemVT = ST->getMemoryVT().getSimpleVT();
    int64_t Scale = getMemScaleForVT(MemVT);

    // Fold materialized PC-relative addresses back into a single *.PCR store:
    //   addr = ADDI(ADDTPC(sym), sym) [+ const]
    //   store [addr] -> *.pcr [sym+const]
    SDValue PcrSym;
	    if (selectPcrSymbolAddr(ST->getBasePtr(), PcrSym)) {
	      unsigned Opc = 0;
	      switch (MemVT.SimpleTy) {
	      case MVT::i8:
	        Opc = LinxISA::SB_PCR;
	        break;
	      case MVT::i16:
	        Opc = LinxISA::SH_PCR;
	        break;
	      case MVT::i32:
	      case MVT::f32:
	        Opc = LinxISA::SW_PCR;
	        break;
	      case MVT::i64:
	      case MVT::f64:
	        Opc = LinxISA::SD_PCR;
	        break;
	      default:
	        Opc = 0;
	        break;
	      }

      if (Opc) {
        SDValue Ops[] = {ST->getValue(), PcrSym, ST->getChain()};
        SDNode *Res = CurDAG->getMachineNode(Opc, DL, MVT::Other, Ops);
        ReplaceNode(N, Res);
        return;
      }
    }

    // Prefer reg-offset addressing when the address matches `base + (idx<<sh)`
    // and the shift matches the store-width scale.
    SDValue BaseRO, IndexRO;
    unsigned Shift = 0;
    if (selectMemAddrRegOffset(ST->getBasePtr(), BaseRO, IndexRO, Shift)) {
      unsigned ExpectedShift = 0;
      unsigned Opc = 0;
      switch (MemVT.SimpleTy) {
      case MVT::i8:
        ExpectedShift = 0;
        Opc = LinxISA::SB;
        break;
      case MVT::i16:
        ExpectedShift = 1;
        Opc = LinxISA::SH;
        break;
      case MVT::i32:
        ExpectedShift = 2;
        Opc = LinxISA::SW;
        break;
      case MVT::f32:
        ExpectedShift = 2;
        Opc = LinxISA::SW;
        break;
      case MVT::i64:
        ExpectedShift = 3;
        Opc = LinxISA::SD;
        break;
      case MVT::f64:
        ExpectedShift = 3;
        Opc = LinxISA::SD;
        break;
      default:
        Opc = 0;
        break;
      }

      if (Opc && Shift == ExpectedShift) {
        SDValue Ops[] = {ST->getValue(), BaseRO, IndexRO, ST->getChain()};
        SDNode *Res = CurDAG->getMachineNode(Opc, DL, MVT::Other, Ops);
        ReplaceNode(N, Res);
        return;
      }
    }

    unsigned Opc = 0;
    switch (MemVT.SimpleTy) {
    case MVT::i1:
      // LLVM may represent boolean stores as i1 in memory. Store a byte (0/1).
      Opc = LinxISA::SBI;
      break;
    case MVT::i8:
      Opc = LinxISA::SBI;
      break;
    case MVT::i16:
      Opc = LinxISA::SHI;
      break;
    case MVT::i32:
      Opc = LinxISA::SWI;
      break;
    case MVT::f32:
      Opc = LinxISA::SWI;
      break;
    case MVT::i64:
      Opc = LinxISA::SDI;
      break;
    case MVT::f64:
      Opc = LinxISA::SDI;
      break;
    default:
      report_fatal_error("Linx: unsupported store type");
    }

    SDValue Base, Off;
    selectMemAddr(ST->getBasePtr(), Base, Off, Scale);

    SDValue Ops[] = {ST->getValue(), Base, Off, ST->getChain()};
    SDNode *Res = CurDAG->getMachineNode(Opc, DL, MVT::Other, Ops);
    ReplaceNode(N, Res);
    return;
  }

  case LinxISD::BR_CC: {
    SDLoc DL(N);
    SDValue Chain = N->getOperand(0);
    ISD::CondCode CC = cast<CondCodeSDNode>(N->getOperand(1))->get();
    SDValue LHS = N->getOperand(2);
    SDValue RHS = N->getOperand(3);
    SDValue Dest = N->getOperand(4);

    bool SwapOps = false;
    unsigned BrOpc = selectBrOpcode(CC, SwapOps);
    if (SwapOps)
      std::swap(LHS, RHS);

    SDValue Ops[] = {LHS, RHS, Dest, Chain};
    SDNode *Res = CurDAG->getMachineNode(BrOpc, DL, MVT::Other, Ops);
    ReplaceNode(N, Res);
    return;
  }

  case LinxISD::SETCC: {
    SDLoc DL(N);
    SDValue LHS = N->getOperand(0);
    SDValue RHS = N->getOperand(1);
    ISD::CondCode CC = cast<CondCodeSDNode>(N->getOperand(2))->get();

    bool SwapOps = false;
    unsigned CmpOpc = selectSetCCOpcode(CC, SwapOps);
    if (SwapOps)
      std::swap(LHS, RHS);

    ReplaceNode(N, CurDAG->getMachineNode(CmpOpc, DL, N->getValueType(0), LHS,
                                          RHS));
    return;
  }
  }

  SelectCode(N);
}
