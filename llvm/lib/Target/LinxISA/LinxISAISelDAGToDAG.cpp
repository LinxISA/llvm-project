      SDValue TileOpImm =
          CurDAG->getTargetConstant(TILEOP_TROWMAX, DL, MVT::i64);
      SDValue SizeImm = CurDAG->getTargetConstant(TSize, DL, MVT::i64);
      SDValue DTypeImm = CurDAG->getTargetConstant(DType, DL, MVT::i64);
