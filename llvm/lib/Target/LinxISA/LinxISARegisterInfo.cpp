LinxISARegisterInfo::getCallPreservedMask(const MachineFunction &MF,
                                          CallingConv::ID CC) const {
  return CSR_Linx_RegMask;
}

BitVector LinxISARegisterInfo::getReservedRegs(const MachineFunction &MF) const {
  BitVector Reserved(getNumRegs());
  Reserved.set(LinxISA::R0);
  Reserved.set(LinxISA::R1); // sp
  Reserved.set(LinxISA::R10); // ra
  if (MF.getSubtarget().getFrameLowering()->hasFP(MF)) {
    Reserved.set(LinxISA::R18); // s8 / frame pointer
  }
  Reserved.set(LinxISA::T1);
  Reserved.set(LinxISA::T2);
  Reserved.set(LinxISA::T3);
  Reserved.set(LinxISA::T4);
  Reserved.set(LinxISA::U1);
  Reserved.set(LinxISA::U2);
  Reserved.set(LinxISA::U3);
  Reserved.set(LinxISA::U4);
  return Reserved;
}

Register LinxISARegisterInfo::getFrameRegister(const MachineFunction &MF) const {
  if (MF.getSubtarget().getFrameLowering()->hasFP(MF)) {
    return LinxISA::R18; // s8
  }
  return LinxISA::R1; // sp
}

static int64_t getMemScale(unsigned Opcode) {
  switch (Opcode) {
  case LinxISA::ADDIri:
  case LinxISA::SUBIri:
  case LinxISA::ADDIWri:
  case LinxISA::SUBIWri:
    return 1;
  case LinxISA::LBI:
  case LinxISA::LBUI:
  case LinxISA::SBI:
    return 1;
  case LinxISA::LHI:
  case LinxISA::LHUI:
  case LinxISA::SHI:
    return 2;
  case LinxISA::LWI:
  case LinxISA::LWUI:
  case LinxISA::SWI:
    return 4;
  case LinxISA::LDI:
  case LinxISA::SDI:
    return 8;
  default:
    return 1;
  }
}

static Register scavengeScratchGPR(MachineBasicBlock::iterator II,
                                   RegScavenger *RS, int SPAdj,
                                   const char *Context) {
  if (!RS)
    report_fatal_error(Twine("Linx: ") + Context +
                       " frame index elimination requires RegScavenger");

  Register BaseReg =
      RS->scavengeRegisterBackwards(LinxISA::GPRRegClass, II,
                                    /*RestoreAfter=*/true, SPAdj,
                                    /*AllowSpill=*/true);
  if (!BaseReg)
    report_fatal_error(Twine("Linx: failed to scavenge scratch register for ") +
                       Context);
  return BaseReg;
}

static void materializeFramePlusOffset(MachineInstr &MI,
                                       MachineBasicBlock::iterator II,
                                       const TargetInstrInfo &TII,
                                       Register BaseReg,
                                       Register FrameReg,
                                       int64_t OffsetBytes) {
  MachineBasicBlock &MBB = *MI.getParent();
  DebugLoc DL = MI.getDebugLoc();

  // Emit a chain of 12-bit/24-bit chunks so frame index elimination keeps
  // working even for very large stack frames generated by libc sources.
  int64_t Remaining = OffsetBytes;
  Register Src = FrameReg;
  while (Remaining != 0) {
    const bool IsPos = Remaining > 0;
    const uint64_t Abs =
        IsPos ? static_cast<uint64_t>(Remaining)
              : static_cast<uint64_t>(-Remaining);
    const uint64_t Chunk = std::min<uint64_t>(Abs, (1u << 24) - 1);
    const bool UseLongImm = Chunk > 4095;
    const unsigned Opc =
        IsPos ? (UseLongImm ? LinxISA::HLADDIri : LinxISA::ADDIri)
              : (UseLongImm ? LinxISA::HLSUBIri : LinxISA::SUBIri);

    BuildMI(MBB, II, DL, TII.get(Opc), BaseReg).addReg(Src).addImm(Chunk);
    Src = BaseReg;
    Remaining = IsPos ? Remaining - static_cast<int64_t>(Chunk)
                      : Remaining + static_cast<int64_t>(Chunk);
  }

  if (OffsetBytes == 0) {
    BuildMI(MBB, II, DL, TII.get(LinxISA::ADDIri), BaseReg)
        .addReg(FrameReg)
        .addImm(0);
  }
}

bool LinxISARegisterInfo::eliminateFrameIndex(MachineBasicBlock::iterator II,
                                              int SPAdj,
                                              unsigned FIOperandNum,
                                              RegScavenger *RS) const {
  MachineInstr &MI = *II;
  MachineFunction &MF = *MI.getParent()->getParent();
  const auto &TII = *MF.getSubtarget().getInstrInfo();
  const MachineFrameInfo &MFI = MF.getFrameInfo();
  const Register FrameReg = getFrameRegister(MF);

  const int FrameIndex = MI.getOperand(FIOperandNum).getIndex();

  // The frame index offset is computed relative to the stack pointer value at
  // the end of the prologue. If this instruction is inside a call sequence,
  // SP has been adjusted by SPAdj (tracked by PEI); incorporate it here.
  int64_t OffsetBytes =
      MFI.getObjectOffset(FrameIndex) + MFI.getStackSize() + SPAdj;

  // Reg-offset addressing forms do not have an immediate displacement field;
  // materialize the stack-object base address into a temporary register.
  switch (MI.getOpcode()) {
  case LinxISA::LB:
  case LinxISA::LBU:
  case LinxISA::LH:
  case LinxISA::LHU:
  case LinxISA::LW:
  case LinxISA::LWU:
  case LinxISA::LD:
  case LinxISA::SB:
  case LinxISA::SH:
  case LinxISA::SW:
  case LinxISA::SD: {
    if (OffsetBytes == 0) {
      MI.getOperand(FIOperandNum)
          .ChangeToRegister(FrameReg, /*isDef=*/false);
      return false;
    }

    Register BaseReg =
        scavengeScratchGPR(II, RS, SPAdj, "reg-offset stack access");
    materializeFramePlusOffset(MI, II, TII, BaseReg, FrameReg, OffsetBytes);

    MI.getOperand(FIOperandNum).ChangeToRegister(BaseReg, /*isDef=*/false);
    return false;
  }
  default:
    break;
  }

  // Tile pseudo stack accesses carry a FrameIndex in operand #0. Materialize
  // a base register and rewrite the FrameIndex operand into that register.
  switch (MI.getOpcode()) {
  case LinxISA::PSEUDO_TMA_TLOAD:
  case LinxISA::PSEUDO_TMA_TLOAD_ANY:
  case LinxISA::PSEUDO_TMA_TSTORE: {
    if (OffsetBytes == 0) {
      MI.getOperand(FIOperandNum).ChangeToRegister(FrameReg, /*isDef=*/false);
      return false;
    }

    Register BaseReg = scavengeScratchGPR(II, RS, SPAdj, "tile stack access");
    materializeFramePlusOffset(MI, II, TII, BaseReg, FrameReg, OffsetBytes);

    MI.getOperand(FIOperandNum).ChangeToRegister(BaseReg, /*isDef=*/false);
    return false;
  }
  default:
    break;
  }

  const int64_t Scale = getMemScale(MI.getOpcode());
  const bool UnsignedImm =
      MI.getOpcode() == LinxISA::ADDIri || MI.getOpcode() == LinxISA::SUBIri ||
      MI.getOpcode() == LinxISA::ADDIWri || MI.getOpcode() == LinxISA::SUBIWri;
  if (OffsetBytes % Scale != 0)
    report_fatal_error("Linx: stack object offset is not naturally aligned");

  int64_t ScaledOff = OffsetBytes / Scale;
  int64_t ExtraImm = 0;
  if (MI.getOperand(FIOperandNum + 1).isImm()) {
    ExtraImm = MI.getOperand(FIOperandNum + 1).getImm();
    ScaledOff += ExtraImm;
  }

  if (UnsignedImm ? !isUInt<12>(ScaledOff) : !isInt<12>(ScaledOff)) {
    // Fall back to materializing the full byte offset in a scratch register.
    // Keep the original instruction and rewrite it as [scratch + 0].
    if (!MI.getOperand(FIOperandNum + 1).isImm())
      report_fatal_error("Linx: unsupported non-immediate frame index operand");

    Register BaseReg = scavengeScratchGPR(II, RS, SPAdj, "stack access");
    materializeFramePlusOffset(MI, II, TII, BaseReg, FrameReg,
                               OffsetBytes + ExtraImm * Scale);

    MI.getOperand(FIOperandNum).ChangeToRegister(BaseReg, /*isDef=*/false);
    MI.getOperand(FIOperandNum + 1).ChangeToImmediate(0);
    return false;
  }

  MI.getOperand(FIOperandNum).ChangeToRegister(FrameReg, /*isDef=*/false);
  MI.getOperand(FIOperandNum + 1).ChangeToImmediate(ScaledOff);
  return false;
}
